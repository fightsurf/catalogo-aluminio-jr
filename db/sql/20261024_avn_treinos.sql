CREATE TABLE IF NOT EXISTS public.avn_exercicios (
 id BIGSERIAL PRIMARY KEY,
 slug VARCHAR(150) NOT NULL UNIQUE,
 nome VARCHAR(160) NOT NULL,
 grupo_id BIGINT NOT NULL REFERENCES public.avn_exercicio_grupos(id),
 equipamento VARCHAR(100) NOT NULL DEFAULT 'Livre',
 instrucoes TEXT NOT NULL DEFAULT '',
 midia_url TEXT,
 midia_tipo VARCHAR(12) NOT NULL DEFAULT 'imagem',
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT avn_exercicios_tipo CHECK (midia_tipo IN ('imagem','gif','video'))
);
CREATE INDEX IF NOT EXISTS avn_exercicios_grupo ON public.avn_exercicios(grupo_id,nome);
CREATE TABLE IF NOT EXISTS public.avn_planos_treino (
 id BIGSERIAL PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES public.avn_usuario(id) ON DELETE RESTRICT,
 nome VARCHAR(160) NOT NULL,
 descricao TEXT NOT NULL DEFAULT '',
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS avn_planos_usuario ON public.avn_planos_treino(usuario_id,ativo,atualizado_em DESC);
CREATE TABLE IF NOT EXISTS public.avn_plano_dias (
 id BIGSERIAL PRIMARY KEY,
 plano_id BIGINT NOT NULL REFERENCES public.avn_planos_treino(id) ON DELETE CASCADE,
 dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
 UNIQUE(plano_id,dia_semana)
);
CREATE TABLE IF NOT EXISTS public.avn_plano_itens (
 id BIGSERIAL PRIMARY KEY,
 plano_dia_id BIGINT NOT NULL REFERENCES public.avn_plano_dias(id) ON DELETE CASCADE,
 exercicio_id BIGINT NOT NULL REFERENCES public.avn_exercicios(id) ON DELETE RESTRICT,
 posicao SMALLINT NOT NULL CHECK (posicao BETWEEN 0 AND 99),
 series SMALLINT NOT NULL DEFAULT 3 CHECK (series BETWEEN 1 AND 30),
 repeticoes VARCHAR(30) NOT NULL DEFAULT '10',
 carga_kg NUMERIC(8,2) CHECK (carga_kg IS NULL OR (carga_kg >= 0 AND carga_kg <= 2000)),
 descanso_seg SMALLINT NOT NULL DEFAULT 60 CHECK (descanso_seg BETWEEN 0 AND 3600),
 observacoes VARCHAR(500) NOT NULL DEFAULT '',
 UNIQUE(plano_dia_id,posicao)
);
CREATE TABLE IF NOT EXISTS public.avn_treino_sessoes (
 id BIGSERIAL PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES public.avn_usuario(id) ON DELETE RESTRICT,
 plano_id BIGINT NOT NULL REFERENCES public.avn_planos_treino(id) ON DELETE RESTRICT,
 dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
 realizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 observacoes VARCHAR(1000) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS avn_sessoes_usuario ON public.avn_treino_sessoes(usuario_id,realizado_em DESC);
CREATE TABLE IF NOT EXISTS public.avn_treino_sessao_itens (
 id BIGSERIAL PRIMARY KEY,
 sessao_id BIGINT NOT NULL REFERENCES public.avn_treino_sessoes(id) ON DELETE CASCADE,
 exercicio_id BIGINT NOT NULL REFERENCES public.avn_exercicios(id) ON DELETE RESTRICT,
 posicao SMALLINT NOT NULL CHECK (posicao BETWEEN 0 AND 99),
 series_realizadas SMALLINT NOT NULL CHECK (series_realizadas BETWEEN 0 AND 30),
 repeticoes_realizadas VARCHAR(30) NOT NULL DEFAULT '',
 carga_kg NUMERIC(8,2) CHECK (carga_kg IS NULL OR (carga_kg >= 0 AND carga_kg <= 2000)),
 observacoes VARCHAR(500) NOT NULL DEFAULT '',
 UNIQUE(sessao_id,posicao)
);
